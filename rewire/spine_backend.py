"""Optional runtime adapter: run sg-urban-spine transforms as SaaS Middleware processors.

SaaS RTI already knows how to deploy a processor (git clone + install.sh), execute it in a working directory
(execute.sh <config> <wd>), stream `trigger:progress/output` lines and push outputs to a DOR, locally, over SSH, or
on NSCC (native adapter) or in Docker. This module makes any spine transform look like such a processor, so the
spine can use SaaS as a backend without changing either side:

    python -m rewire.spine_backend export <transform.yaml> <out_dir> [--config default]
                                          [--root R --include P --requirements F --extra-pip PINS]
        -> out_dir/{descriptor.json, processor.py, execute.sh, install.sh, spine_backend.py, src/...}
           (a self-contained SaaS processor: no absolute paths, can be committed and deployed anywhere)
    python -m rewire.spine_backend run <transform.yaml> <wd>
        -> what processor.py does: <wd>/<input> parquet + optional <wd>/parameters -> <wd>/<output> parquet

Only runnable spine runtimes (python, subprocess, docker, cwl) can be exported; `external` transforms (e.g. DUCT
WRF/PALM/Scout) already ARE SaaS processors, so SaaS runs them directly and the spine adapter's prepare()/collect()
convert Silver <-> their working-directory files.
"""
from __future__ import annotations

import argparse
import contextlib
import json
import os
import shlex
import shutil
import sys
from pathlib import Path

DATA_FORMAT = "parquet"
SPINE_PIP = "git+https://github.com/tetratorus/saas-middleware@sg-urban-spine"


def _spine():
    from spine import transform  # imported lazily: SaaS itself does not depend on spine
    return transform


def data_type(source: str) -> str:
    """silver:buildings -> spine.silver.buildings ; gold:duct.mva_wind_corridor/x -> spine.gold.duct.mva_wind_corridor.x"""
    layer, ref = source.split(":", 1)
    return f"spine.{layer}.{ref.replace('/', '.')}"


def saas_descriptor(transform_yaml: str | os.PathLike, configurations=("default",)) -> dict:
    desc = _spine().load_descriptor(transform_yaml)
    d = desc.data
    if d["runtime"]["type"] == "external":
        raise ValueError(f"{desc.id} is runtime external: run its own SaaS processor instead (see runtime.notes)")
    inputs = [{"name": i["name"], "data_type": data_type(i["source"]), "data_format": DATA_FORMAT}
              for i in d["inputs"]]
    inputs.append({"name": "parameters", "data_type": "JSONObject", "data_format": "json",
                   "data_schema": d.get("parameters", {"type": "object"})})
    outputs = [{"name": o["name"], "data_type": data_type(f"gold:{desc.id}/{o['name']}"), "data_format": DATA_FORMAT}
               for o in d["outputs"]]
    return {"name": f"spine-{desc.id.replace('.', '-').replace('_', '-')}", "input": inputs, "output": outputs,
            "configurations": list(configurations)}


def run(transform_yaml: str | os.PathLike, wd: str | os.PathLike) -> int:
    """SaaS working-directory contract around spine.transform.invoke. Returns a process exit code."""
    from spine.lake import read_table, write_table
    t = _spine()
    wd = Path(wd)
    desc = t.load_descriptor(transform_yaml)
    print("trigger:progress:0", flush=True)
    inputs = {}
    for spec in desc.data["inputs"]:
        p = wd / spec["name"]
        if p.exists():
            inputs[spec["name"]] = read_table(p)
        elif spec.get("optional"):
            inputs[spec["name"]] = None
        else:
            print(f"missing input object '{spec['name']}' in {wd}", file=sys.stderr)
            return 1
    params_path = wd / "parameters"
    params = t.resolve_params(desc, json.loads(params_path.read_text()) if params_path.exists() else {})
    print("trigger:progress:10", flush=True)
    # wrapped models may print their own SaaS triggers (e.g. DUCT processors); keep RTI stdout to this processor's
    with contextlib.redirect_stdout(sys.stderr):
        outputs = t.invoke(desc, inputs, params)
    print("trigger:progress:90", flush=True)
    for name, df in outputs.items():
        write_table(df, wd / name)
        print(f"trigger:output:{name}", flush=True)
    print("trigger:progress:100", flush=True)
    return 0


EXECUTE_SH = """#!/bin/bash
# generated by rewire/spine_backend.py; SaaS RTI calls: execute.sh <configuration> <working_directory>
set -e
cd "$(dirname "$0")"
source venv/bin/activate
python processor.py "$2"
"""

INSTALL_SH = """#!/bin/bash
# generated by rewire/spine_backend.py; SaaS RTI calls: install.sh <configuration>
set -e
cd "$(dirname "$0")"
python3.10 -m venv venv
source venv/bin/activate
pip install {spine_pip} {extra}{requirements}
"""

PROCESSOR_PY = """# generated by rewire/spine_backend.py from {transform_id} {version}; self-contained, paths relative to this dir
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from spine_backend import run

TRANSFORM = HERE.joinpath(*{transform_parts!r})

if __name__ == "__main__":
    sys.exit(run(TRANSFORM, sys.argv[1]))
"""

SRC = "src"
_IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", ".git", ".pytest_cache", "venv", "golden", "tests")


def _rel(path: Path, root: Path) -> Path:
    rel = Path(os.path.relpath(path.resolve(), root))
    if rel.is_absolute() or ".." in rel.parts:
        raise ValueError(f"{path} is outside the bundle root {root}")
    return rel


def _copy(path: Path, dest: Path) -> None:
    if path.is_dir():
        shutil.copytree(path, dest, ignore=_IGNORE, dirs_exist_ok=True)
    else:
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, dest)


def export(transform_yaml: str | os.PathLike, out_dir: str | os.PathLike, configurations=("default",),
           extra_pip: str = "", root: str | os.PathLike | None = None, include=(), requirements=()) -> Path:
    """Write a self-contained SaaS processor directory for one transform:

    descriptor.json, processor.py, execute.sh, install.sh, a copy of this module (spine_backend.py) and, under src/,
    the transform directory plus any `include` paths, all at their paths relative to `root` (default: the transform
    directory's parent) so adapters that locate upstream code relative to themselves keep working. `requirements`
    files (relative to root; a requirements.txt next to transform.yaml is picked up automatically) are copied and
    installed by install.sh. Nothing in the output refers to the machine it was generated on.
    """
    transform_yaml = Path(transform_yaml).resolve()
    tdir = transform_yaml.parent
    root = Path(root).resolve() if root else tdir.parent
    out = Path(out_dir)
    desc = saas_descriptor(transform_yaml, configurations)
    meta = _spine().load_descriptor(transform_yaml).data
    if out.exists() and any(out.iterdir()):
        if not (out / "processor.py").exists():
            raise FileExistsError(f"{out} is not empty and not a previous export")
        shutil.rmtree(out)
    out.mkdir(parents=True)
    reqs = [Path(r) for r in requirements]
    if (tdir / "requirements.txt").exists():
        reqs.append(_rel(tdir / "requirements.txt", root))
    for path in [tdir, *(root / i for i in include), *(root / r for r in reqs)]:
        rel = _rel(path, root)
        if not path.exists():
            raise FileNotFoundError(path)
        _copy(path, out / SRC / rel)
    shutil.copy2(Path(__file__).resolve(), out / "spine_backend.py")
    (out / "descriptor.json").write_text(json.dumps(desc, indent=2))
    (out / "processor.py").write_text(PROCESSOR_PY.format(
        transform_id=meta["id"], version=meta.get("version", ""),
        transform_parts=(SRC, *_rel(transform_yaml, root).parts)))
    req_args = "".join(f" -r {shlex.quote((Path(SRC) / r).as_posix())}" for r in dict.fromkeys(reqs))
    install = INSTALL_SH.format(spine_pip=shlex.quote(SPINE_PIP), extra=extra_pip, requirements=req_args)
    for name, body in (("execute.sh", EXECUTE_SH), ("install.sh", install)):
        (out / name).write_text(body)
        (out / name).chmod(0o755)
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m rewire.spine_backend")
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("export"); e.add_argument("transform"); e.add_argument("out")
    e.add_argument("--config", action="append", default=None); e.add_argument("--extra-pip", default="")
    e.add_argument("--root", default=None, help="bundle root (default: parent of the transform dir)")
    e.add_argument("--include", action="append", default=[], help="extra path under --root to bundle")
    e.add_argument("--requirements", action="append", default=[], help="requirements file under --root")
    r = sub.add_parser("run"); r.add_argument("transform"); r.add_argument("wd")
    a = ap.parse_args(argv)
    if a.cmd == "export":
        print(export(a.transform, a.out, a.config or ["default"], a.extra_pip, a.root, a.include, a.requirements))
        return 0
    return run(a.transform, a.wd)


if __name__ == "__main__":
    sys.exit(main())
